"""
NYC flight-delay ETL
====================
raw CSVs  ->  clean DataFrames  ->  QA checks  ->  SQLite star schema  ->  Power BI CSVs

Run from the project root:   python etl/pipeline.py
Every QA result is recorded as one of:
    PASS   the check held
    FIXED  a problem existed in the raw data and the pipeline corrected it
    WARN   a known limitation; the data is kept and the impact is documented
    FAIL   a rule was broken; the pipeline stops before loading
"""
from __future__ import annotations

import logging
import sqlite3
import sys
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd
from pandas.tseries.holiday import USFederalHolidayCalendar

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "raw"
DB_PATH = ROOT / "warehouse" / "flights.db"
SCHEMA_PATH = ROOT / "sql" / "schema.sql"
EXPORT_DIR = ROOT / "powerbi" / "data"
QA_REPORT = ROOT / "docs" / "qa_report.md"

RAW_TABLES = ["flights", "airlines", "airports", "planes", "weather"]
DATA_YEAR = 2013
DELAY_THRESHOLD_MIN = 15  # FAA convention: a delay is 15+ minutes

log = logging.getLogger("etl")


# ----------------------------------------------------------------------
# QA recorder
# ----------------------------------------------------------------------
@dataclass
class Result:
    status: str
    layer: str
    name: str
    detail: str


class QA:
    def __init__(self) -> None:
        self.results: list[Result] = []

    def check(self, layer: str, name: str, ok: bool, detail: str, if_bad: str = "FAIL") -> bool:
        status = "PASS" if ok else if_bad
        self.results.append(Result(status, layer, name, detail))
        log.info("[%s] %s - %s", status, name, detail)
        return ok

    def fixed(self, layer: str, name: str, detail: str) -> None:
        self.results.append(Result("FIXED", layer, name, detail))
        log.info("[FIXED] %s - %s", name, detail)

    @property
    def failures(self) -> list[Result]:
        return [r for r in self.results if r.status == "FAIL"]

    def write_report(self, path: Path) -> None:
        def esc(s: str) -> str:
            return str(s).replace("|", "/").replace("\n", " ")

        counts = pd.Series([r.status for r in self.results]).value_counts()
        lines = [
            "# Data quality report",
            "",
            "Generated by `etl/pipeline.py` on every run. Nothing here is hand-edited.",
            "",
            "Status legend: **PASS** check held, **FIXED** raw problem corrected by the ETL, "
            "**WARN** known limitation kept and documented, **FAIL** pipeline stops.",
            "",
            "Summary: " + ", ".join(f"{counts.get(s, 0)} {s}" for s in ["PASS", "FIXED", "WARN", "FAIL"]),
            "",
        ]
        for layer in dict.fromkeys(r.layer for r in self.results):
            lines += [f"## {layer}", "", "| Status | Check | Detail |", "|---|---|---|"]
            for r in (x for x in self.results if x.layer == layer):
                lines.append(f"| {r.status} | {esc(r.name)} | {esc(r.detail)} |")
            lines.append("")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(lines), encoding="utf-8")


# ----------------------------------------------------------------------
# Extract
# ----------------------------------------------------------------------
def extract() -> None:
    """Snapshot the source tables to data/raw so every later step is reproducible offline."""
    import nycflights13 as nf  # pip install nycflights13

    RAW_DIR.mkdir(parents=True, exist_ok=True)
    for name in RAW_TABLES:
        df = getattr(nf, name)
        df.to_csv(RAW_DIR / f"{name}.csv", index=False)
        log.info("extracted %-9s %8d rows", name, len(df))


def read_raw() -> dict[str, pd.DataFrame]:
    # keep_default_na=False so a real code such as "NA" is never silently read as missing
    return {
        n: pd.read_csv(RAW_DIR / f"{n}.csv", keep_default_na=False, na_values=[""])
        for n in RAW_TABLES
    }


# ----------------------------------------------------------------------
# Helpers
# ----------------------------------------------------------------------
def hhmm_to_minutes(s: pd.Series) -> pd.Series:
    """Convert hhmm integers (e.g. 1345, and 2400 for midnight) to minute-of-day."""
    m = (s // 100) * 60 + (s % 100)
    return (m % 1440).astype("Int64")


MANUFACTURER_MAP = {
    "AIRBUS INDUSTRIE": "AIRBUS",
    "CANADAIR LTD": "CANADAIR",
    "MCDONNELL DOUGLAS AIRCRAFT CO": "MCDONNELL DOUGLAS",
    "MCDONNELL DOUGLAS CORPORATION": "MCDONNELL DOUGLAS",
}

# Destinations present in flights but absent from the airports table (Puerto Rico / USVI).
# Names supplemented manually so joins to dim_airport are complete. lat/lon are left NULL
# rather than guessed. They are flagged is_supplemented = 1.
SUPPLEMENTAL_AIRPORTS = {
    "BQN": "Rafael Hernandez Airport",
    "SJU": "Luis Munoz Marin International Airport",
    "STT": "Cyril E King Airport",
    "PSE": "Mercedita Airport",
}


def weather_key(origin: pd.Series, ts_utc: pd.Series) -> pd.Series:
    return origin + "-" + ts_utc.dt.strftime("%Y%m%d%H")


# ----------------------------------------------------------------------
# Raw-layer QA (before any cleaning)
# ----------------------------------------------------------------------
def qa_raw(raw: dict[str, pd.DataFrame], qa: QA) -> None:
    f, a, ap, p, w = (raw[k] for k in RAW_TABLES)
    L = "1. Raw data profile"

    qa.check(L, "Row counts loaded", True,
             ", ".join(f"{k}={len(v):,}" for k, v in raw.items()))
    qa.check(L, "No fully duplicated flight rows", f.duplicated().sum() == 0,
             f"{f.duplicated().sum()} duplicates")
    qa.check(L, "Weather key (origin, time_hour) is unique", not w.duplicated(["origin", "time_hour"]).any(),
             f"{w.duplicated(['origin', 'time_hour']).sum()} duplicate keys")
    qa.check(L, "Planes tailnum is unique", not p.tailnum.duplicated().any(), "no duplicate tail numbers")
    qa.check(L, "Airports faa code is unique", not ap.faa.duplicated().any(), "no duplicate codes")

    orphan_carrier = (~f.carrier.isin(a.carrier)).sum()
    qa.check(L, "Every flight carrier exists in airlines", orphan_carrier == 0, f"{orphan_carrier} orphan rows")

    orphan_origin = (~f.origin.isin(ap.faa)).sum()
    qa.check(L, "Every flight origin exists in airports", orphan_origin == 0, f"{orphan_origin} orphan rows")

    orphan_dest = ~f.dest.isin(ap.faa)
    qa.check(L, "Every flight destination exists in airports", orphan_dest.sum() == 0,
             f"{orphan_dest.sum():,} flights ({orphan_dest.mean():.2%}) go to {sorted(f.dest[orphan_dest].unique())} "
             "which are missing from airports. Supplemented in cleaning.", if_bad="FIXED")

    tails = f.tailnum.dropna()
    orphan_tail = ~tails.isin(p.tailnum)
    qa.check(L, "Every flight tail number exists in planes", orphan_tail.sum() == 0,
             f"{orphan_tail.sum():,} flights ({orphan_tail.sum() / len(f):.1%} of all flights) have no plane record. "
             "Kept with LEFT JOIN, so aircraft-age analysis covers matched flights only.", if_bad="WARN")

    cancelled = f.dep_time.isna()
    qa.check(L, "Missing tailnum occurs only on cancelled flights", f.tailnum.isna().sum() == (f.tailnum.isna() & cancelled).sum(),
             f"{f.tailnum.isna().sum():,} missing tailnums; all on flights with no departure time")

    # Internal consistency: dep_delay must equal dep_time - sched_dep_time (mod 24h)
    dep_m, sch_m = hhmm_to_minutes(f.dep_time), hhmm_to_minutes(f.sched_dep_time)
    ok_rows = f.dep_delay.notna()
    diff = (dep_m[ok_rows] - sch_m[ok_rows] - f.dep_delay[ok_rows]).astype("int64") % 1440
    qa.check(L, "dep_delay agrees with dep_time minus sched_dep_time", (diff == 0).all(),
             f"{(diff != 0).sum()} of {ok_rows.sum():,} departed flights disagree")

    arr_m, sarr_m = hhmm_to_minutes(f.arr_time), hhmm_to_minutes(f.sched_arr_time)
    ok_arr = f.arr_delay.notna()
    diff = (arr_m[ok_arr] - sarr_m[ok_arr] - f.arr_delay[ok_arr]).astype("int64") % 1440
    qa.check(L, "arr_delay agrees with arr_time minus sched_arr_time", (diff == 0).all(),
             f"{(diff != 0).sum()} of {ok_arr.sum():,} arrivals disagree")

    qa.check(L, "dep_time and dep_delay are missing together", (f.dep_time.isna() == f.dep_delay.isna()).all(),
             "identical missingness pattern")
    qa.check(L, "air_time and arr_delay are missing together", (f.air_time.isna() == f.arr_delay.isna()).all(),
             "identical missingness pattern")

    qa.check(L, "Scheduled hour in 0-23, minute in 0-59", f.hour.between(0, 23).all() and f.minute.between(0, 59).all(),
             "all in range")
    qa.check(L, "distance and air_time are positive", (f.distance > 0).all() and (f.air_time.dropna() > 0).all(),
             "all positive")
    qa.check(L, "No delay beyond 48 hours (implausible)", f[["dep_delay", "arr_delay"]].abs().max().max() <= 2880,
             f"largest delay is {f.dep_delay.max():,.0f} min ({f.dep_delay.max() / 60:.1f} h). Kept: plausible.")

    n_routes = (f.groupby(["origin", "dest"]).distance.nunique() > 1)
    qa.check(L, "Each route has a single distance", not n_routes.any(),
             f"{int(n_routes.sum())} route(s) have 2 distinct distances ({', '.join('-'.join(i) for i in n_routes[n_routes].index)}). "
             "Distance is analysed per flight, never assumed per route.", if_bad="WARN")

    # Weather validity
    qa.check(L, "Weather: humidity within 0-100 %", w.humid.dropna().between(0, 100).all(), "all in range")
    qa.check(L, "Weather: visibility within 0-10 mi", w.visib.between(0, 10).all(), "all in range")
    qa.check(L, "Weather: precipitation is non-negative", (w.precip >= 0).all(), "all non-negative")
    bad_wind = w.wind_speed > 100
    qa.check(L, "Weather: wind speed physically plausible (<= 100 mph)", not bad_wind.any(),
             f"{bad_wind.sum()} reading(s) up to {w.wind_speed.max():,.0f} mph. Set to NULL in cleaning.", if_bad="FIXED")
    qa.check(L, "Weather: pressure within 900-1100 mb", w.pressure.dropna().between(900, 1100).all(), "all in range")
    qa.check(L, "Weather: temperature within -30 to 115 F", w.temp.dropna().between(-30, 115).all(), "all in range")

    expected_hours = 365 * 24 * 3
    qa.check(L, "Weather covers every hour for each airport", len(w) >= expected_hours,
             f"{len(w):,} hourly rows vs {expected_hours:,} possible, so {expected_hours - len(w):,} hours have no observation.", if_bad="WARN")
    for col, pct in (w.isna().mean()).items():
        if pct > 0.05:
            qa.check(L, f"Weather: {col} completeness", False,
                     f"{pct:.0%} missing. Not used as a primary driver.", if_bad="WARN")

    py = p.year.dropna()
    qa.check(L, "Planes: year built within 1900-2013", py.between(1900, DATA_YEAR).all(),
             f"range {int(py.min())}-{int(py.max())}; {p.year.isna().sum()} missing")
    qa.check(L, "Planes: speed column is usable", p.speed.notna().mean() > 0.5,
             f"{p.speed.notna().mean():.1%} populated. Column dropped.", if_bad="FIXED")
    n_mfr = p.manufacturer.nunique()
    n_std = p.manufacturer.replace(MANUFACTURER_MAP).nunique()
    qa.check(L, "Planes: manufacturer names are standardised", n_mfr == n_std,
             f"{n_mfr} raw spellings collapse to {n_std} (e.g. AIRBUS INDUSTRIE to AIRBUS, three McDonnell Douglas variants).",
             if_bad="FIXED")


# ----------------------------------------------------------------------
# Transform
# ----------------------------------------------------------------------
def transform(raw: dict[str, pd.DataFrame]) -> dict[str, pd.DataFrame]:
    f, a, ap, p, w = (raw[k].copy() for k in RAW_TABLES)

    # ---- dim_date --------------------------------------------------
    dates = pd.date_range(f"{DATA_YEAR}-01-01", f"{DATA_YEAR}-12-31", freq="D")
    hol = USFederalHolidayCalendar().holidays(start=dates.min(), end=dates.max(), return_name=True)
    dim_date = pd.DataFrame({"date": dates})
    dim_date["year"] = dim_date.date.dt.year
    dim_date["quarter"] = dim_date.date.dt.quarter
    dim_date["month"] = dim_date.date.dt.month
    dim_date["month_name"] = dim_date.date.dt.month_name()
    dim_date["week_of_year"] = dim_date.date.dt.isocalendar().week.astype(int)
    dim_date["weekday_num"] = dim_date.date.dt.dayofweek + 1
    dim_date["weekday_name"] = dim_date.date.dt.day_name()
    dim_date["is_weekend"] = (dim_date.weekday_num >= 6).astype(int)
    dim_date["holiday_name"] = dim_date.date.map(hol)
    dim_date["is_us_holiday"] = dim_date.holiday_name.notna().astype(int)
    dim_date["date"] = dim_date.date.dt.strftime("%Y-%m-%d")

    # ---- dim_airline -----------------------------------------------
    dim_airline = a.rename(columns={"name": "airline_name"})[["carrier", "airline_name"]]

    # ---- dim_airport (+ supplement) --------------------------------
    dim_airport = ap.rename(columns={"alt": "altitude_ft", "tz": "tz_offset"})
    dim_airport["is_supplemented"] = 0
    missing = sorted(set(f.dest) - set(dim_airport.faa))
    extra = pd.DataFrame({"faa": missing, "name": [SUPPLEMENTAL_AIRPORTS[m] for m in missing], "is_supplemented": 1})
    dim_airport = pd.concat([dim_airport, extra], ignore_index=True)
    dim_airport["altitude_ft"] = dim_airport.altitude_ft.astype("Int64")
    dim_airport = dim_airport[["faa", "name", "lat", "lon", "altitude_ft", "tz_offset", "dst", "tzone", "is_supplemented"]]

    # ---- dim_plane -------------------------------------------------
    dim_plane = p.rename(columns={"year": "year_built", "type": "plane_type", "engine": "engine_type",
                                  "manufacturer": "manufacturer_raw"}).drop(columns=["speed"])
    dim_plane["manufacturer"] = dim_plane.manufacturer_raw.replace(MANUFACTURER_MAP)
    dim_plane["year_built"] = dim_plane.year_built.astype("Int64")
    dim_plane["plane_age_2013"] = (DATA_YEAR - dim_plane.year_built).astype("Int64")
    dim_plane = dim_plane[["tailnum", "year_built", "plane_age_2013", "plane_type", "manufacturer_raw",
                           "manufacturer", "model", "engines", "seats", "engine_type"]]

    # ---- fact_weather ----------------------------------------------
    w["time_hour_utc"] = pd.to_datetime(w.time_hour, utc=True)
    w["weather_key"] = weather_key(w.origin, w.time_hour_utc)
    w.loc[w.wind_speed > 100, "wind_speed"] = np.nan  # 1,048 mph is a sensor error
    w["is_precip"] = (w.precip > 0).astype(int)
    w["is_freezing"] = np.where(w.temp.isna(), np.nan, (w.temp <= 32).astype(float))
    w["visib_band"] = pd.cut(w.visib, [-0.01, 1, 3, 9.99, 10],
                             labels=["1) under 1 mi", "2) 1 to 3 mi", "3) 3 to 10 mi", "4) 10 mi (clear)"]).astype(str)
    w["wind_band"] = pd.cut(w.wind_speed, [-0.01, 10, 20, 1000],
                            labels=["1) calm (under 10 mph)", "2) breezy (10-20 mph)", "3) windy (20+ mph)"]).astype(object)
    w["wind_band"] = w.wind_band.where(w.wind_band.notna(), None)
    w["time_hour_utc"] = w.time_hour_utc.dt.strftime("%Y-%m-%d %H:%M:%S")
    fact_weather = w.rename(columns={"temp": "temp_f", "dewp": "dewp_f", "humid": "humid_pct",
                                     "wind_dir": "wind_dir_deg", "wind_speed": "wind_speed_mph",
                                     "wind_gust": "wind_gust_mph", "precip": "precip_in",
                                     "pressure": "pressure_mb", "visib": "visib_mi"})
    fact_weather["is_freezing"] = fact_weather.is_freezing.astype("Int64")
    fact_weather = fact_weather[["weather_key", "origin", "time_hour_utc", "temp_f", "dewp_f", "humid_pct",
                                 "wind_dir_deg", "wind_speed_mph", "wind_gust_mph", "precip_in", "pressure_mb",
                                 "visib_mi", "is_precip", "is_freezing", "visib_band", "wind_band"]]

    # ---- fact_flight -----------------------------------------------
    f["flight_id"] = np.arange(1, len(f) + 1)
    f["flight_date"] = pd.to_datetime(dict(year=f.year, month=f.month, day=f.day)).dt.strftime("%Y-%m-%d")
    f["route"] = f.origin + "-" + f.dest
    f["sched_dep_minute_of_day"] = hhmm_to_minutes(f.sched_dep_time)
    f["dep_minute_of_day"] = hhmm_to_minutes(f.dep_time)

    cancelled = f.dep_time.isna()
    incomplete = ~cancelled & f.arr_delay.isna()  # departed but no arrival delay: diverted / record incomplete
    f["flight_status"] = np.select([cancelled, incomplete], ["Cancelled", "Diverted_or_Incomplete"], "Completed")
    f["is_cancelled"] = cancelled.astype(int)
    f["is_dep_delayed"] = pd.array(np.where(f.dep_delay.isna(), pd.NA, (f.dep_delay >= DELAY_THRESHOLD_MIN).astype(float)), dtype="Float64").astype("Int64")
    f["is_arr_delayed"] = pd.array(np.where(f.arr_delay.isna(), pd.NA, (f.arr_delay >= DELAY_THRESHOLD_MIN).astype(float)), dtype="Float64").astype("Int64")
    f["time_recovered_min"] = (f.dep_delay - f.arr_delay).astype("Int64")

    keys = weather_key(f.origin, pd.to_datetime(f.time_hour, utc=True))
    f["weather_key"] = keys.where(keys.isin(set(fact_weather.weather_key)), None)

    for c in ["dep_delay", "arr_delay", "air_time"]:
        f[c] = f[c].astype("Int64")
    fact_flight = f.rename(columns={"flight": "flight_number", "hour": "sched_dep_hour", "dep_delay": "dep_delay_min",
                                    "arr_delay": "arr_delay_min", "air_time": "air_time_min",
                                    "distance": "distance_mi"})
    fact_flight = fact_flight[["flight_id", "flight_date", "carrier", "flight_number", "tailnum", "origin", "dest",
                               "route", "sched_dep_hour", "sched_dep_minute_of_day", "dep_minute_of_day",
                               "dep_delay_min", "arr_delay_min", "air_time_min", "distance_mi", "flight_status",
                               "is_cancelled", "is_dep_delayed", "is_arr_delayed", "time_recovered_min",
                               "weather_key"]]

    return {"dim_date": dim_date, "dim_airline": dim_airline, "dim_airport": dim_airport, "dim_plane": dim_plane,
            "fact_weather": fact_weather, "fact_flight": fact_flight}


# ----------------------------------------------------------------------
# Clean-layer QA (after transform, before load)
# ----------------------------------------------------------------------
def qa_clean(raw: dict[str, pd.DataFrame], t: dict[str, pd.DataFrame], qa: QA) -> None:
    L = "2. Clean data checks (before load)"
    ff, fw = t["fact_flight"], t["fact_weather"]

    qa.check(L, "Flight row count preserved through cleaning", len(ff) == len(raw["flights"]),
             f"{len(raw['flights']):,} raw, {len(ff):,} clean")
    qa.check(L, "flight_id is unique", ff.flight_id.is_unique, "surrogate key unique")
    qa.check(L, "Weather key is unique", fw.weather_key.is_unique, "unique")
    for child, col, parent, pcol in [("fact_flight", "carrier", "dim_airline", "carrier"),
                                     ("fact_flight", "origin", "dim_airport", "faa"),
                                     ("fact_flight", "dest", "dim_airport", "faa"),
                                     ("fact_flight", "flight_date", "dim_date", "date"),
                                     ("fact_weather", "origin", "dim_airport", "faa")]:
        orphans = (~t[child][col].isin(t[parent][pcol])).sum()
        qa.check(L, f"FK {child}.{col} to {parent}", orphans == 0, f"{orphans} orphans")
    tails = ff.tailnum.dropna()
    o = (~tails.isin(t["dim_plane"].tailnum)).sum()
    qa.check(L, "FK fact_flight.tailnum to dim_plane (optional)", o == 0,
             f"{o:,} flights unmatched. Expected: plane table is incomplete.", if_bad="WARN")
    nw = ff.weather_key.isna().sum()
    qa.check(L, "Flights matched to a weather observation", nw == 0,
             f"{nw:,} flights ({nw / len(ff):.2%}) have no weather row. Excluded from weather analysis only.", if_bad="WARN")

    # Status logic
    canc = ff[ff.is_cancelled == 1]
    qa.check(L, "Cancelled flights carry no delay or arrival data",
             canc.dep_delay_min.isna().all() and canc.arr_delay_min.isna().all(), f"{len(canc):,} cancelled flights")
    vc = ff.flight_status.value_counts()
    qa.check(L, "Status split accounts for every flight", vc.sum() == len(ff),
             ", ".join(f"{k}={v:,}" for k, v in vc.items()) +
             ". 'Diverted_or_Incomplete' is inferred (departed but no arrival delay); the source has no status field.")
    qa.check(L, "Wind speed outlier removed", fw.wind_speed_mph.max() <= 100, f"max now {fw.wind_speed_mph.max():.1f} mph")
    qa.check(L, "Manufacturer names standardised",
             t["dim_plane"].manufacturer.nunique() < t["dim_plane"].manufacturer_raw.nunique(),
             f"{t['dim_plane'].manufacturer_raw.nunique()} to {t['dim_plane'].manufacturer.nunique()} distinct values")
    qa.check(L, "Delay flags follow the 15-minute rule",
             ((ff.dep_delay_min >= 15).astype("Int64").dropna() == ff.is_dep_delayed.dropna()).all(),
             "is_dep_delayed equals (dep_delay_min >= 15) on every departed flight")


# ----------------------------------------------------------------------
# Load + reconcile
# ----------------------------------------------------------------------
LOAD_ORDER = ["dim_date", "dim_airline", "dim_airport", "dim_plane", "fact_weather", "fact_flight"]


def load(t: dict[str, pd.DataFrame]) -> sqlite3.Connection:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    if DB_PATH.exists():
        DB_PATH.unlink()
    con = sqlite3.connect(DB_PATH)
    con.execute("PRAGMA foreign_keys = ON")
    con.executescript(SCHEMA_PATH.read_text())
    for name in LOAD_ORDER:
        df = t[name].astype(object).where(t[name].notna(), None)  # NaN/NA -> NULL
        df.to_sql(name, con, if_exists="append", index=False, chunksize=50_000)
        log.info("loaded %-13s %8d rows", name, len(df))
    con.commit()
    return con


def qa_reconcile(con: sqlite3.Connection, t: dict[str, pd.DataFrame], qa: QA) -> None:
    L = "3. Post-load reconciliation (warehouse vs source frames)"
    for name in LOAD_ORDER:
        n = con.execute(f"SELECT COUNT(*) FROM {name}").fetchone()[0]
        qa.check(L, f"Row count {name}", n == len(t[name]), f"warehouse {n:,}, expected {len(t[name]):,}")

    s = con.execute("SELECT SUM(dep_delay_min), SUM(arr_delay_min), SUM(distance_mi) FROM fact_flight").fetchone()
    e = (int(t["fact_flight"].dep_delay_min.sum()), int(t["fact_flight"].arr_delay_min.sum()),
         int(t["fact_flight"].distance_mi.sum()))
    qa.check(L, "Checksums of delay and distance columns match", tuple(s) == e, f"warehouse {s}, expected {e}")

    n_flights = len(t["fact_flight"])
    fanout = con.execute("""
        SELECT COUNT(*)
        FROM fact_flight f
        JOIN dim_airline  al ON al.carrier = f.carrier
        JOIN dim_airport  ao ON ao.faa     = f.origin
        JOIN dim_airport  ad ON ad.faa     = f.dest
        JOIN dim_date     d  ON d.date     = f.flight_date
        LEFT JOIN dim_plane    p ON p.tailnum     = f.tailnum
        LEFT JOIN fact_weather w ON w.weather_key = f.weather_key
    """).fetchone()[0]
    qa.check(L, "Full star join neither drops nor duplicates flights", fanout == n_flights,
             f"joined {fanout:,} rows vs {n_flights:,} flights")

    inner_w = con.execute("SELECT COUNT(*) FROM fact_flight f JOIN fact_weather w ON w.weather_key = f.weather_key").fetchone()[0]
    expected = int(t["fact_flight"].weather_key.notna().sum())
    qa.check(L, "INNER JOIN to weather keeps exactly the matched flights", inner_w == expected,
             f"{inner_w:,} joined vs {expected:,} with a weather key")

    fk = con.execute("PRAGMA foreign_key_check").fetchall()
    qa.check(L, "SQLite foreign_key_check is clean", len(fk) == 0, f"{len(fk)} violations")


def export_powerbi(t: dict[str, pd.DataFrame]) -> None:
    EXPORT_DIR.mkdir(parents=True, exist_ok=True)
    for name in LOAD_ORDER:
        t[name].to_csv(EXPORT_DIR / f"{name}.csv", index=False)
        log.info("exported %s.csv", name)


