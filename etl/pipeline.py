def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s  %(message)s", datefmt="%H:%M:%S")
    if not (RAW_DIR / "flights.csv").exists():
        extract()
    raw = read_raw()
    qa = QA()

    qa_raw(raw, qa)
    tables = transform(raw)
    qa_clean(raw, tables, qa)
    if qa.failures:
        qa.write_report(QA_REPORT)
        log.error("QA failed: %s", [r.name for r in qa.failures])
        return 1

    con = load(tables)
    qa_reconcile(con, tables, qa)
    con.close()
    qa.write_report(QA_REPORT)
    if qa.failures:
        log.error("Reconciliation failed: %s", [r.name for r in qa.failures])
        return 1
    export_powerbi(tables)
    log.info("ETL complete. QA report: %s", QA_REPORT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
